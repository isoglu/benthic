"""Zitierstil: Erkennen, Form und Vollständigkeit einzelner Angaben, Hinweise zur Liste (offline)."""

import unittest

from benthic import style

NUMPY_FOUND = {"doi": "10.1038/s41586-020-2649-2", "type": "journal-article", "volume": "585",
               "issue": "7825", "pages": "357–362", "author_count": 26}
APA_OK = ("Harris, C. R., Millman, K. J., & van der Walt, S. J. (2020). Array programming with NumPy. "
          "Nature, 585(7825), 357–362. https://doi.org/10.1038/s41586-020-2649-2")
APA_SHORT = "Harris, C. R., et al. (2020). Array programming with NumPy. Nature."
IEEE_OK = ('[1] C. R. Harris et al., "Array programming with NumPy," Nature, vol. 585, no. 7825, '
           "pp. 357-362, 2020, doi: 10.1038/s41586-020-2649-2.")
VANCOUVER = "1. Harris CR, Millman KJ, van der Walt SJ. Array programming with NumPy. Nature. 2020;585(7825):357-62."


def codes(issues):
    return [i["code"] for i in issues]


class Stil(unittest.TestCase):
    def test_guess(self):
        self.assertEqual(style.guess(APA_OK), "apa")
        self.assertEqual(style.guess(IEEE_OK), "ieee")
        self.assertEqual(style.guess(VANCOUVER), "vancouver")
        self.assertEqual(style.guess("Harris, C. R. (2020) Array programming with NumPy. Nature, 585, pp. 357-362."), "harvard")
        self.assertIsNone(style.guess("Array programming with NumPy"))

    def test_complete_apa_entry_is_clean(self):
        self.assertEqual(style.check_entry(APA_OK, "apa", NUMPY_FOUND), [])

    def test_incomplete_apa_entry(self):
        found = codes(style.check_entry(APA_SHORT, "apa", NUMPY_FOUND))
        for code in ("no_volume", "no_issue", "no_pages", "no_doi"):
            self.assertIn(code, found)
        self.assertNotIn("et_al", found)  # 26 Autor:innen: "et al." ist üblich (auch bei doi.org)
        self.assertIn("et_al", codes(style.check_entry(APA_SHORT, "apa", {**NUMPY_FOUND, "author_count": 3})))

    def test_ieee_rules(self):
        self.assertEqual(style.check_entry(IEEE_OK, "ieee", NUMPY_FOUND), [])
        found = codes(style.check_entry(APA_OK, "ieee", NUMPY_FOUND))
        self.assertIn("number", found)
        self.assertIn("authors_initials_first", found)
        self.assertIn("title_quotes", found)
        self.assertIn("other_style", found)

    def test_plain_doi_in_apa(self):
        entry = APA_OK.replace("https://doi.org/", "doi:")
        self.assertIn("doi_link", codes(style.check_entry(entry, "apa", NUMPY_FOUND)))

    def test_article_numbers_count_as_volume_and_pages(self):
        walters = ("Walters, W. H., & Wilder, E. I. (2023). Fabrication and errors in the bibliographic citations "
                   "generated by ChatGPT. Scientific Reports, 13, 14045. https://doi.org/10.1038/s41598-023-41032-5")
        found = codes(style.check_entry(walters, "apa", {"type": "journal-article", "volume": "13", "issue": "1"}))
        self.assertNotIn("no_volume", found)
        self.assertIn("no_issue", found)
        plos = ("Piwowar, H. A., Day, R. S., & Fridsma, D. B. (2007). Sharing detailed research data is associated "
                "with increased citation rate. PLoS ONE, 2(3), e308. https://doi.org/10.1371/journal.pone.0000308")
        self.assertEqual(style.check_entry(plos, "apa", {"type": "journal-article", "volume": "2", "issue": "3",
                                                         "pages": "e308"}), [])

    def test_without_metadata_only_form(self):
        self.assertNotIn("no_pages", codes(style.check_entry(APA_SHORT, "apa", None)))

    def test_list_checks(self):
        rows = [
            {"order": 0, "input": "Smith, J. (2020). Zebra studies. Journal of Z, 1(1), 1-2.", "claimed": {"authors": ["Smith"]}, "verdict": "verified"},
            {"order": 1, "input": "Adams, K. (2019). Apple studies. Journal of A, 2(1), 3-4.", "claimed": {"authors": ["Adams"]}, "verdict": "verified"},
            {"order": 2, "input": IEEE_OK, "claimed": {"authors": ["Harris"]}, "verdict": "verified", "doi": "10.1/x"},
            {"order": 3, "input": IEEE_OK, "claimed": {"authors": ["Harris"]}, "verdict": "verified", "doi": "10.1/x"},
        ]
        report = style.check_list(rows)
        self.assertTrue(report["applicable"])
        self.assertEqual(report["style"], "apa")
        list_codes = [i["code"] for i in report["list"]]
        self.assertIn("mixed", list_codes)
        self.assertIn("order", list_codes)
        self.assertIn("duplicates", list_codes)
        self.assertIn("2", report["entries"])  # die IEEE-Angabe in einer APA-Liste

    def test_numbering_gaps_and_choice(self):
        rows = [{"order": i, "input": f"[{n}] A. Author, \"Title number {n},\" J. Test, vol. 1, pp. 1-2, 2020."}
                for i, n in enumerate((1, 2, 4))]
        report = style.check_list(rows)
        self.assertEqual(report["detected"], "ieee")
        self.assertIn("gaps", [i["code"] for i in report["list"]])
        self.assertEqual(style.check_list(rows, "apa")["style"], "apa")

    def test_bibtex_is_not_style_checked(self):
        rows = [{"order": 0, "input": "@article{x, title={A}}"}]
        self.assertFalse(style.check_list(rows)["applicable"])


if __name__ == "__main__":
    unittest.main()
